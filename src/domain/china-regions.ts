export const CHINA_REGIONS: readonly RegionProvinceNode[] = RAW_CHINA_REGIONS.map(([code, name, shortName, cities]) => ({
    code,
    name,
    shortName,
    cities: cities.map(([cityCode, cityName, districts = []]) => ({
        code: cityCode,
        name: cityName,
        districts: districts.map(([dCode, dName]) => ({ code: dCode, name: dName })),
    })),
}));

export interface ResolvedChinaCity {
    provinceCode: string;
    provinceName: string;
    provinceShortName: string;
    cityCode: string;
    cityName: string;
    canonicalCity: string;
}

const CITY_BY_CODE = new Map<string, ResolvedChinaCity>();
const CITY_BY_ALIAS = new Map<string, ResolvedChinaCity>();
const PROVINCE_BY_CODE = new Map<string, RegionProvinceNode>();
const DISTRICT_BY_CODE = new Map<string, { province: RegionProvinceNode; city: RegionCityNode; district: RegionDistrictNode }>();

export function normalizeChinaCityName(raw: string | undefined): string {
    if (!raw) return "";
    let s = raw.trim();
    if (!s) return "";
    // 去掉自治区/省前缀（例如 "四川省成都市" -> "成都市"）
    s = s.replace(/^[\u4e00-\u9fa5]{2,8}?(?:省|自治区|特别行政区)\s*/, "");
    // 去掉行政后缀
    s = s
        .replace(/(?:土家族苗族|藏族羌族|哈尼族彝族|壮族苗族|布依族苗族|苗族侗族|蒙古族藏族|朝鲜族|蒙古|哈萨克|白族|傣族|景颇族|傈僳族|彝族|藏族|回族|维吾尔族)自治州$/, "")
        .replace(/(?:市|地区|自治州|盟|特别行政区|省)$/, "")
        .trim();
    return s;
}

for (const prov of CHINA_REGIONS) {
    PROVINCE_BY_CODE.set(prov.code, prov);
    for (const city of prov.cities) {
        const canonicalCity = normalizeChinaCityName(city.name) || city.name;
        const resolved: ResolvedChinaCity = {
            provinceCode: prov.code,
            provinceName: prov.name,
            provinceShortName: prov.shortName,
            cityCode: city.code,
            cityName: city.name,
            canonicalCity,
        };
        CITY_BY_CODE.set(city.code, resolved);
        CITY_BY_ALIAS.set(city.name, resolved);
        CITY_BY_ALIAS.set(canonicalCity, resolved);
        for (const dist of city.districts) {
            DISTRICT_BY_CODE.set(dist.code, { province: prov, city, district: dist });
        }
    }
}

export function getProvinceByCode(code: string | undefined): RegionProvinceNode | undefined {
    return code ? PROVINCE_BY_CODE.get(code.trim()) : undefined;
}

export function getCitiesByProvinceCode(provinceCode: string | undefined): readonly RegionCityNode[] {
    return getProvinceByCode(provinceCode)?.cities ?? [];
}

export function getDistrictsByCityCode(provinceCode: string | undefined, cityCode: string | undefined): readonly RegionDistrictNode[] {
    const prov = getProvinceByCode(provinceCode);
    if (!prov || !cityCode) return [];
    return prov.cities.find((c) => c.code === cityCode.trim())?.districts ?? [];
}

/**
 * 将城市编码或任意城市写法（如 "510100"、"成都"、"成都市"、"四川省成都市"）解析为标准城市结构
 */
export function resolveChinaCity(input: string | undefined): ResolvedChinaCity | null {
    if (!input) return null;
    const trimmed = input.trim();
    if (!trimmed) return null;

    if (CITY_BY_CODE.has(trimmed)) {
        return CITY_BY_CODE.get(trimmed)!;
    }

    const direct = CITY_BY_ALIAS.get(trimmed);
    if (direct) return direct;

    const stripped = normalizeChinaCityName(trimmed);
    if (stripped && CITY_BY_ALIAS.has(stripped)) {
        return CITY_BY_ALIAS.get(stripped)!;
    }

    // 自由文本包含匹配：优先匹配完整带"市/州/盟"的名字，再匹配短名（按长度降序避免误匹配）
    let best: ResolvedChinaCity | null = null;
    let bestScore = -1;
    for (const prov of CHINA_REGIONS) {
        const provMatched = trimmed.includes(prov.name) || trimmed.includes(prov.shortName);
        for (const city of prov.cities) {
            const canonical = normalizeChinaCityName(city.name) || city.name;
            if (trimmed.includes(city.name)) {
                const score = city.name.length * 10 + (provMatched ? 50 : 0);
                if (score > bestScore) {
                    bestScore = score;
                    best = CITY_BY_CODE.get(city.code)!;
                }
            } else if (canonical.length >= 2 && trimmed.includes(canonical)) {
                // 防止 "吉林省长春市" 把省名 "吉林" 误判成 "吉林市"
                const isProvincePrefix = canonical === prov.shortName && trimmed.includes(`${prov.shortName}省`);
                const score = canonical.length * 8 + (provMatched ? 40 : 0) - (isProvincePrefix ? 100 : 0);
                if (score > bestScore && score > 0) {
                    bestScore = score;
                    best = CITY_BY_CODE.get(city.code)!;
                }
            }
        }
    }
    return best;
}

/**
 * 从自由文本中解析完整的省/市/区三级结构，同时保留原始文本 rawText
 */
export function parseChinaRegionFromText(
    rawText: string | undefined,
    kind: ContactLocationKind = "resident",
): ContactLocation | null {
    if (!rawText) return null;
    const cleaned = rawText.trim();
    if (!cleaned) return null;

    const cityHit = resolveChinaCity(cleaned);
    if (cityHit) {
        const prov = PROVINCE_BY_CODE.get(cityHit.provinceCode);
        const cityNode = prov?.cities.find((c) => c.code === cityHit.cityCode);
        let districtHit: RegionDistrictNode | undefined;
        if (cityNode) {
            for (const d of cityNode.districts) {
                const shortD = d.name.replace(/(?:区|县|市|街道|镇)$/, "");
                if (cleaned.includes(d.name) || (shortD.length >= 2 && cleaned.includes(shortD))) {
                    districtHit = d;
                    break;
                }
            }
        }
        return {
            kind,
            provinceCode: cityHit.provinceCode,
            provinceName: cityHit.provinceName,
            cityCode: cityHit.cityCode,
            cityName: cityHit.cityName,
            ...(districtHit ? { districtCode: districtHit.code, districtName: districtHit.name } : {}),
            rawText: cleaned,
        };
    }

    // 仅匹配到省份
    for (const prov of CHINA_REGIONS) {
        if (cleaned.includes(prov.name) || cleaned.includes(prov.shortName)) {
            return {
                kind,
                provinceCode: prov.code,
                provinceName: prov.name,
                rawText: cleaned,
            };
        }
    }

    return {
        kind,
        rawText: cleaned,
    };
}

export function normalizeContactLocation(raw: unknown, fallbackKind: ContactLocationKind): ContactLocation | undefined {
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) return undefined;
    const rec = raw as Record<string, unknown>;
    const kind: ContactLocationKind = rec.kind === "hometown" || rec.kind === "resident" ? rec.kind : fallbackKind;
    const provinceCode = typeof rec.provinceCode === "string" ? rec.provinceCode.trim() || undefined : undefined;
    const provinceName = typeof rec.provinceName === "string" ? rec.provinceName.trim() || undefined : undefined;
    const cityCode = typeof rec.cityCode === "string" ? rec.cityCode.trim() || undefined : undefined;
    const cityName = typeof rec.cityName === "string" ? rec.cityName.trim() || undefined : undefined;
    const districtCode = typeof rec.districtCode === "string" ? rec.districtCode.trim() || undefined : undefined;
    const districtName = typeof rec.districtName === "string" ? rec.districtName.trim() || undefined : undefined;
    const rawText = typeof rec.rawText === "string" ? rec.rawText.trim() || undefined : undefined;

    if (!provinceCode && !provinceName && !cityCode && !cityName && !districtCode && !districtName && !rawText) {
        return undefined;
    }

    // 若只有 code 或 name 缺省，自动补全标准名
    const resolvedCity = cityCode ? CITY_BY_CODE.get(cityCode) : (cityName ? resolveChinaCity(cityName) : null);
    const resolvedDist = districtCode ? DISTRICT_BY_CODE.get(districtCode) : undefined;
    const prov = (provinceCode ? PROVINCE_BY_CODE.get(provinceCode) : undefined)
        ?? (resolvedCity ? PROVINCE_BY_CODE.get(resolvedCity.provinceCode) : undefined)
        ?? resolvedDist?.province;

    return {
        kind,
        ...(prov ? { provinceCode: prov.code, provinceName: prov.name } : { ...(provinceCode ? { provinceCode } : {}), ...(provinceName ? { provinceName } : {}) }),
        ...(resolvedCity ? { cityCode: resolvedCity.cityCode, cityName: resolvedCity.cityName } : { ...(cityCode ? { cityCode } : {}), ...(cityName ? { cityName } : {}) }),
        ...(resolvedDist ? { districtCode: resolvedDist.district.code, districtName: resolvedDist.district.name } : { ...(districtCode ? { districtCode } : {}), ...(districtName ? { districtName } : {}) }),
        ...(rawText ? { rawText } : {}),
    };
}

export function normalizeContactLocations(raw: unknown): ContactLocations {
    if (!raw) return {};
    if (Array.isArray(raw)) {
        const result: ContactLocations = {};
        for (const item of raw) {
            if (!item || typeof item !== "object") continue;
            const kind = (item as { kind?: unknown }).kind === "hometown" ? "hometown" : "resident";
            const norm = normalizeContactLocation(item, kind);
            if (norm) {
                if (norm.kind === "resident" && !result.resident) result.resident = norm;
                if (norm.kind === "hometown" && !result.hometown) result.hometown = norm;
            }
        }
        return result;
    }
    if (typeof raw === "object") {
        const obj = raw as Record<string, unknown>;
        const resident = normalizeContactLocation(obj.resident, "resident");
        const hometown = normalizeContactLocation(obj.hometown, "hometown");
        return {
            ...(resident ? { resident } : {}),
            ...(hometown ? { hometown } : {}),
        };
    }
    return {};
}

export function parseContactLocationsAttr(raw: unknown): ContactLocations {
    if (!raw) return {};
    if (typeof raw === "object") return normalizeContactLocations(raw);
    if (typeof raw !== "string") return {};
    const trimmed = raw.trim();
    if (!trimmed) return {};
    try {
        return normalizeContactLocations(JSON.parse(decodeURIComponent(trimmed)));
    } catch {
        try {
            return normalizeContactLocations(JSON.parse(trimmed));
        } catch {
            return {};
        }
    }
}

export function serializeContactLocationsAttr(locations: ContactLocations): string {
    const clean = normalizeContactLocations(locations);
    if (!clean.resident && !clean.hometown) return "";
    return encodeURIComponent(JSON.stringify(clean));
}

export function formatContactLocation(loc: ContactLocation | undefined): string {
    if (!loc) return "";
    const parts: string[] = [];
    if (loc.provinceName) parts.push(loc.provinceName);
    if (loc.cityName && loc.cityName !== loc.provinceName) parts.push(loc.cityName);
    if (loc.districtName) parts.push(loc.districtName);
    if (parts.length > 0) return parts.join(" · ");
    return loc.rawText?.trim() ?? "";
}

export function isSameCityLocation(a: ContactLocation | string | undefined, b: ContactLocation | string | undefined): boolean {
    const resolveLoc = (v: ContactLocation | string | undefined): ResolvedChinaCity | null => {
        if (!v) return null;
        if (typeof v === "string") return resolveChinaCity(v);
        if (v.cityCode && CITY_BY_CODE.has(v.cityCode)) return CITY_BY_CODE.get(v.cityCode)!;
        if (v.cityName) return resolveChinaCity(v.cityName);
        if (v.rawText) return resolveChinaCity(v.rawText);
        return null;
    };
    const ca = resolveLoc(a);
    const cb = resolveLoc(b);
    if (ca && cb) return ca.cityCode === cb.cityCode;
    const rawA = typeof a === "string" ? normalizeChinaCityName(a) : normalizeChinaCityName(a?.cityName || a?.rawText);
    const rawB = typeof b === "string" ? normalizeChinaCityName(b) : normalizeChinaCityName(b?.cityName || b?.rawText);
    return Boolean(rawA && rawB && rawA === rawB);
}
